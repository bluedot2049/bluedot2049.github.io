// 拼成一串：臉 → 手 → 身體
export function kaoText(f, h, b) {
  const face = FACES[f] || FACES[0], hand = HANDS[h] || HANDS[0], body = BODIES[b] || BODIES[0];
  return body.w.replace('%', hand.w.replace('%', face.t));
}

// 網路上送的代號：臉、手、身體各 4 位元，0 是什麼都沒擺
export const kaoCode = (f, h, b) => (f & 15) | ((h & 15) << 4) | ((b & 15) << 8);
export const kaoParts = (c) => [c & 15, (c >> 4) & 15, (c >> 8) & 15];
// 從 was 換到 now 有沒有多擺或換了一層；只是收掉幾層（做完一輪收手、走開放下姿勢、時間到）不算，頭上不再冒字、不再出聲
export const kaoGrew = (was, now) => { const a = kaoParts(was), b = kaoParts(now); return b.some((v, i) => v && v !== a[i]); };
// 頭上冒什麼：只冒臉（基本情緒），手和姿勢看身體就懂。臉換成另一張才冒；只換手、身體或收掉不冒
export const kaoFaceNew = (was, now) => { const f = now & 15; return f !== 0 && f !== (was & 15); };
// 擺出來時照哪個舊表情出聲：手優先，再看臉
export const kaoLike = (c) => { const [f, h] = kaoParts(c); return HANDS[h]?.like || FACES[f]?.like || null; };
// 要轉向的身體：鏡頭在 yaw 這個方向（從角色看出去，跟 heading 同一套）時，身體該朝哪
export function kaoFacing(c, yaw) {
  const b = BODIES[kaoParts(c)[2]];
  return b?.turn ? yaw - ((b.B?.[1] || 0) + (b.head?.[1] || 0)) : null;
}
export const isKao = (c) => Number.isInteger(c) && c >= 0 && c < 4096 && (c & 15) < FACES.length && ((c >> 4) & 15) < HANDS.length && ((c >> 8) & 15) < BODIES.length;
