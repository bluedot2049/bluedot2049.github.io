Prims = List[Tuple[str, Any]]


def _w(prim, w):
    """w：這一筆的粗細倍數，密的地方裡面的筆畫可以細一點"""
    return prim if w == 1.0 else with_weight(prim, w)


def box(x0, y0, x1, y1, w=1.0, **k):
    """口：封閉的方框"""
    return _w(bar((x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0), **k), w)


def h(x0, x1, y, w=1.0, **k):
    return _w(bar((x0, y), (x1, y), **k), w)


def v(x, y0, y1, w=1.0, **k):
    return _w(bar((x, y0), (x, y1), **k), w)


def earth(cx, cy, r) -> Prims:
    """⊕：田 當部件時的寫法"""
    return [ring(cx, cy, r), h(cx - r, cx + r, cy), v(cx, cy - r, cy + r)]


